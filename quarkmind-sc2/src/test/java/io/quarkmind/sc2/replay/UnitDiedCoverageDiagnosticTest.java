package io.quarkmind.sc2.replay;

import hu.scelight.sc2.rep.factory.RepContent;
import hu.scelight.sc2.rep.factory.RepParserEngine;
import hu.scelight.sc2.rep.model.Replay;
import hu.scelight.sc2.rep.s2prot.Event;
import hu.scelightapi.sc2.rep.model.trackerevents.IBaseUnitEvent;
import hu.scelightapi.sc2.rep.model.trackerevents.ITrackerEvents;
import io.quarkmind.domain.SC2Data;
import io.quarkmind.domain.UnitType;
import io.quarkmind.sc2.intent.TimedIntent;
import io.quarkmind.sc2.intent.UnitDiedIntent;
import io.quarkmind.sc2.mock.Sc2ReplayShared;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIf;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.EnumSet;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * Diagnostic: measures gap between raw tracker UnitDied events and
 * UnitDiedIntents generated by TrackerIntentExtractor.
 * Identifies which unit types have missed deaths and their supply impact.
 *
 * Refs #525
 */
@Tag("diagnostic")
class UnitDiedCoverageDiagnosticTest {

    private static final Path ORACLE_DIR = Path.of(
        "../quarkmind-classifier/data/replay_packs/blizzard_ladder/4.9.3_oracle/restored");

    static boolean oracleExists() {
        if (!Files.isDirectory(ORACLE_DIR)) return false;
        try (var stream = Files.list(ORACLE_DIR)) {
            return stream.anyMatch(p -> p.toString().endsWith(".SC2Replay"));
        } catch (Exception e) { return false; }
    }

    @Test
    @EnabledIf("oracleExists")
    void unitDiedCoverageGap() throws Exception {
        List<Path> replays;
        try (var stream = Files.list(ORACLE_DIR)) {
            replays = stream.filter(p -> p.toString().endsWith(".SC2Replay"))
                .sorted().toList();
        }

        Map<String, long[]> gapByTypeName = new TreeMap<>();
        long totalRawDeaths = 0;
        long totalIntentDeaths = 0;
        long totalMissedSupply = 0;
        int playerRuns = 0;
        long totalTypeChangeEvents = 0;

        for (Path replayPath : replays) {
            Replay parsed;
            try {
                parsed = RepParserEngine.parseReplay(replayPath,
                    EnumSet.of(RepContent.TRACKER_EVENTS, RepContent.DETAILS, RepContent.GAME_EVENTS));
            } catch (Exception e) { continue; }
            if (parsed == null || parsed.trackerEvents == null) continue;
            if (parsed.details == null || parsed.details.getPlayerList().length < 2) continue;

            for (int playerId = 1; playerId <= 2; playerId++) {
                playerRuns++;

                // Build full ownership map from UnitBorn + UnitInit (all units, not just tracked)
                Map<Long, String> fullOwnership = new HashMap<>();
                for (Event raw : parsed.trackerEvents.getEvents()) {
                    int eid = raw.getId();
                    if ((eid == ITrackerEvents.ID_UNIT_BORN || eid == ITrackerEvents.ID_UNIT_INIT)
                        && raw instanceof IBaseUnitEvent ue) {
                        Integer pid = ue.getControlPlayerId();
                        if (pid != null && pid == playerId) {
                            String typeName = String.valueOf(ue.getUnitTypeName()).trim();
                            long tag = ((long) ue.getUnitTagIndex() << 32) | (ue.getUnitTagRecycle() & 0xFFFFFFFFL);
                            fullOwnership.put(tag, typeName);
                        }
                    }
                    if (raw.getId() == ITrackerEvents.ID_UNIT_TYPE_CHANGE) {
                        Integer tagIndex = raw.get("unitTagIndex");
                        Integer tagRecycle = raw.get("unitTagRecycle");
                        if (tagIndex != null && tagRecycle != null) {
                            long tag = ((long) tagIndex << 32) | (tagRecycle & 0xFFFFFFFFL);
                            if (fullOwnership.containsKey(tag)) {
                                totalTypeChangeEvents++;
                                Object newTypeObj = raw.get("unitTypeName");
                                if (newTypeObj != null) {
                                    fullOwnership.put(tag, String.valueOf(newTypeObj).trim());
                                }
                            }
                        }
                    }
                }

                // Count raw UnitDied events for player's non-building units
                int rawDeaths = 0;
                Map<String, Integer> rawDeathsByType = new TreeMap<>();
                for (Event raw : parsed.trackerEvents.getEvents()) {
                    if (raw.getId() != ITrackerEvents.ID_UNIT_DIED) continue;
                    Integer tagIndex = raw.get("unitTagIndex");
                    Integer tagRecycle = raw.get("unitTagRecycle");
                    if (tagIndex == null || tagRecycle == null) continue;
                    long tag = ((long) tagIndex << 32) | (tagRecycle & 0xFFFFFFFFL);
                    String typeName = fullOwnership.get(tag);
                    if (typeName == null) continue; // enemy or unknown owner
                    if (Sc2ReplayShared.BUILDING_NAMES.contains(typeName)) continue; // building
                    rawDeaths++;
                    rawDeathsByType.merge(typeName, 1, Integer::sum);
                }

                // Count UnitDiedIntents from extractor
                List<TimedIntent> intents;
                try {
                    intents = TrackerIntentExtractor.extractFromReplay(parsed, playerId);
                } catch (Exception e) { continue; }

                Map<String, Integer> intentDeathsByType = new TreeMap<>();
                for (TimedIntent ti : intents) {
                    if (ti.intent() instanceof UnitDiedIntent d) {
                        intentDeathsByType.merge(d.unitType().name(), 1, Integer::sum);
                    }
                }
                long intentDeaths = intents.stream()
                    .filter(ti -> ti.intent() instanceof UnitDiedIntent).count();

                totalRawDeaths += rawDeaths;
                totalIntentDeaths += intentDeaths;

                // Compute per-type gaps
                for (var entry : rawDeathsByType.entrySet()) {
                    String typeName = entry.getKey();
                    int raw = entry.getValue();
                    UnitType ut = Sc2ReplayShared.toUnitType(typeName);
                    String intentKey = ut != UnitType.UNKNOWN ? ut.name() : typeName;
                    int intent = intentDeathsByType.getOrDefault(intentKey, 0);
                    int gap = raw - intent;
                    if (gap > 0) {
                        gapByTypeName.computeIfAbsent(typeName, k -> new long[3]);
                        gapByTypeName.get(typeName)[0] += raw;
                        gapByTypeName.get(typeName)[1] += intent;
                        gapByTypeName.get(typeName)[2] += gap;

                        int supplyCost = ut != UnitType.UNKNOWN ? SC2Data.supplyCost(ut) : 0;
                        totalMissedSupply += (long) gap * supplyCost;
                    }
                }
            }
        }

        System.out.println("\n=== UnitDied Coverage Diagnostic ===");
        System.out.printf("Player runs: %d%n", playerRuns);
        System.out.printf("Total raw UnitDied (non-building): %d%n", totalRawDeaths);
        System.out.printf("Total UnitDiedIntents generated:   %d%n", totalIntentDeaths);
        System.out.printf("Coverage: %.1f%%%n",
            totalRawDeaths > 0 ? totalIntentDeaths * 100.0 / totalRawDeaths : 100);
        System.out.printf("UnitTypeChange events (player units): %d%n", totalTypeChangeEvents);
        System.out.printf("Total missed supply from gaps: %d%n", totalMissedSupply);

        System.out.println("\nPer-type gaps (raw > intent):");
        System.out.printf("%-30s %8s %8s %8s %8s%n", "TypeName", "Raw", "Intent", "Gap", "Supply");
        for (var entry : gapByTypeName.entrySet()) {
            String typeName = entry.getKey();
            long[] counts = entry.getValue();
            UnitType ut = Sc2ReplayShared.toUnitType(typeName);
            int supplyCost = ut != UnitType.UNKNOWN ? SC2Data.supplyCost(ut) : 0;
            System.out.printf("%-30s %8d %8d %8d %8d%n",
                typeName, counts[0], counts[1], counts[2], counts[2] * supplyCost);
        }
    }
}
