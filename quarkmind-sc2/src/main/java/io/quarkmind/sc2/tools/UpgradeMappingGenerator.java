package io.quarkmind.sc2.tools;

import io.quarkmind.domain.UpgradeType;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

public final class UpgradeMappingGenerator {

    public static void main(String[] args) throws IOException {
        Path outputPath = args.length > 0
                ? Path.of(args[0])
                : Path.of("../quarkmind-classifier/src/upgrade_mapping.py");

        var sb = new StringBuilder();
        sb.append("# Generated by UpgradeMappingGenerator — do not edit manually\n");
        sb.append("UPGRADES = [\n");
        for (UpgradeType type : UpgradeType.values()) {
            sb.append("    \"").append(type.pythonName()).append("\",\n");
        }
        sb.append("]\n");

        Files.createDirectories(outputPath.getParent());
        Files.writeString(outputPath, sb.toString());
        System.out.printf("Wrote %d upgrades to %s%n", UpgradeType.values().length, outputPath.toAbsolutePath());
    }
}
